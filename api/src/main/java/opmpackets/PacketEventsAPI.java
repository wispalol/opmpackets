package opmpackets;

import opmpackets.event.EventManager;
import opmpackets.injector.ChannelInjector;
import opmpackets.manager.InternalPacketListener;
import opmpackets.manager.player.PlayerManager;
import opmpackets.manager.protocol.ProtocolManager;
import opmpackets.manager.server.ServerManager;
import opmpackets.netty.NettyManager;
import opmpackets.protocol.packettype.PacketType;
import opmpackets.protocol.world.states.WrappedBlockState;
import opmpackets.settings.PacketEventsSettings;
import opmpackets.util.logger.JulLegacyLogManager;
import opmpackets.util.LogManager;
import opmpackets.util.PEVersion;
import opmpackets.util.PEVersions;
import opmpackets.util.adventure.AdventureConversionInjector;
import opmpackets.util.mappings.SynchronizedRegistriesHandler;
import opmpackets.util.updatechecker.UpdateChecker;

import java.util.logging.Logger;

public abstract class PacketEventsAPI<T> {

    private final EventManager eventManager = new EventManager();
    private final PacketEventsSettings settings = new PacketEventsSettings();
    private final UpdateChecker updateChecker = new UpdateChecker();
    private final LogManager logManager = LogManager.construct(this);

    public EventManager getEventManager() {
        return eventManager;
    }

    public PacketEventsSettings getSettings() {
        return settings;
    }

    public UpdateChecker getUpdateChecker() {
        return updateChecker;
    }

    public PEVersion getVersion() {
        //Note: The PEVersions class is generated by the auto-version task. Refer to PEVersionTask.kt
        return PEVersions.CURRENT;
    }

    @Deprecated
    public Logger getLogger() {
        return JulLegacyLogManager.getLogger();
    }

    public LogManager getLogManager() {
        return this.logManager;
    }

    public void load() {
        this.getLogManager().info("Loading packetevents...");

        WrappedBlockState.ensureLoad();
        SynchronizedRegistriesHandler.init();
        PacketType.prepare();
        AdventureConversionInjector.inject();

        // Register internal packet listener (should be the first listener)
        // This listener doesn't do any modifications to the packets, just reads data
        this.registerInternalListener();
    }

    protected void registerInternalListener() {
        this.getEventManager().registerListener(new InternalPacketListener());
    }

    public abstract boolean isLoaded();

    public abstract void init();

    public abstract boolean isInitialized();

    public void terminate() {
        try {
            this.getInjector().uninject();
        } catch (Throwable throwable) {
            this.getLogManager().warn("Failed to uninject during termination, this error can be ignored on shutdown", throwable);
        }
        this.getEventManager().unregisterAllListeners();
        AdventureConversionInjector.uninject();
    }

    public abstract boolean isTerminated();

    public abstract T getPlugin();

    public abstract ServerManager getServerManager();

    public abstract ProtocolManager getProtocolManager();

    public abstract PlayerManager getPlayerManager();

    public abstract NettyManager getNettyManager();

    public abstract ChannelInjector getInjector();
}
